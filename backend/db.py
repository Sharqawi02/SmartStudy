from contextlib import contextmanager

import psycopg 
from psycopg.rows import dict_row

from config import DATABASE_CONFIG



@contextmanager
def get_connection():
    conn = psycopg.connect(**DATABASE_CONFIG, row_factory=dict_row)
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db():
    with get_connection() as conn:
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS courses (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                difficulty TEXT NOT NULL CHECK (difficulty IN ('low', 'med', 'high')),
                exam_date TEXT NOT NULL
            )
            """
        )

        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS study_settings (
                id INTEGER PRIMARY KEY CHECK (id = 1),
                hours_per_week INTEGER NOT NULL CHECK (hours_per_week >= 0),
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            )
            """
        )

        conn.execute(
            """
            INSERT INTO study_settings (id, hours_per_week, created_at, updated_at)
            VALUES (1, 8, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
            ON CONFLICT (id) DO NOTHING
            """
        )
