from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row

from config import DATABASE_CONFIG, DEFAULT_HOURS_PER_WEEK



@contextmanager
def get_connection():
    conn = psycopg.connect(**DATABASE_CONFIG, row_factory=dict_row)
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def ensure_user_settings(conn, user_id, hours_per_week=DEFAULT_HOURS_PER_WEEK):
    conn.execute(
        """
        INSERT INTO user_settings (user_id, hours_per_week, created_at, updated_at)
        VALUES (%s, %s, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
        ON CONFLICT (user_id) DO NOTHING
        """,
        (user_id, hours_per_week),
    )


def init_db():
    with get_connection() as conn:
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                full_name TEXT NOT NULL,
                email TEXT NOT NULL,
                password_hash TEXT NOT NULL,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
            """
        )

        conn.execute(
            """
            CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique
            ON users ((LOWER(email)))
            """
        )

        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS courses (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                difficulty TEXT NOT NULL CHECK (difficulty IN ('low', 'med', 'high')),
                exam_date TEXT NOT NULL
            )
            """
        )

        conn.execute(
            """
            ALTER TABLE courses
            ADD COLUMN IF NOT EXISTS user_id INTEGER REFERENCES users(id) ON DELETE CASCADE
            """
        )

        conn.execute(
            """
            CREATE INDEX IF NOT EXISTS courses_user_id_idx
            ON courses (user_id)
            """
        )

        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS user_settings (
                user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
                hours_per_week INTEGER NOT NULL CHECK (hours_per_week >= 0),
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            )
            """
        )

        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS study_plans (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                generated_at TEXT NOT NULL,
                hours_per_week INTEGER NOT NULL CHECK (hours_per_week >= 0),
                suggestion_text TEXT NOT NULL,
                suggestion_source TEXT NOT NULL,
                weekly_focus JSONB NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
            """
        )

        conn.execute(
            """
            ALTER TABLE study_plans
            ADD COLUMN IF NOT EXISTS user_id INTEGER REFERENCES users(id) ON DELETE CASCADE
            """
        )

        conn.execute(
            """
            CREATE INDEX IF NOT EXISTS study_plans_user_id_created_at_idx
            ON study_plans (user_id, created_at DESC, id DESC)
            """
        )
